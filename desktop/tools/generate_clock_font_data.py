"""Extract the unmodified clock glyphs from the firmware's LVGL font sources.

Usage: python desktop/tools/generate_clock_font_data.py /path/to/font/c/files

The input directory must contain lv_font_dseg_90_bpp1.c from VuNMix and
lv_font_montserrat_{10,12,14,16,20,36}.c from LVGL v8.3.11. The output is a
Python module so frozen desktop builds include the fonts without filesystem or
system font dependencies. Only printable ASCII is needed for the device clocks.
See desktop/assets/licenses/clock-preview-fonts.txt for source URLs and licenses.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
from pathlib import Path
import re
import textwrap
import zlib


FONT_NAMES = ("dseg90", "10", "12", "14", "16", "20", "36")


def _array(source: str, name: str) -> list[int]:
    match = re.search(r"\b" + name + r"\[\]\s*=\s*\{(.*?)\};", source, re.S)
    if match is None:
        raise ValueError(f"Missing array: {name}")
    body = re.sub(r"/\*.*?\*/", "", match[1], flags=re.S)
    return [int(value.strip(), 0) for value in body.split(",") if value.strip()]


def extract_font(path: Path, dseg: bool = False) -> dict:
    source = path.read_text(encoding="utf-8")
    bitmap = bytes(_array(source, "glyph_bitmap"))
    glyph_source = re.search(r"glyph_dsc\[\]\s*=\s*\{(.*?)\};", source, re.S)[1]
    glyphs = [dict((key, int(value)) for key, value in re.findall(r"\.(\w+)\s*=\s*(-?\d+)", row))
              for row in re.findall(r"\{([^}]+)\}", glyph_source)]
    scalar = lambda name: int(re.search(r"\." + name + r"\s*=\s*(\d+)", source)[1])
    if scalar("bitmap_format") != 0:
        raise ValueError("Only uncompressed LVGL font sources are supported")
    bpp = scalar("bpp")
    first, last = (48, 58) if dseg else (32, 126)
    packed = bytearray()
    subset = {}
    for codepoint in range(first, last + 1):
        glyph = glyphs[codepoint - first + 1]
        count = (glyph["box_w"] * glyph["box_h"] * bpp + 7) // 8
        start = glyph["bitmap_index"]
        subset[str(codepoint)] = [len(packed), glyph["adv_w"], glyph["box_w"],
                                 glyph["box_h"], glyph["ofs_x"], glyph["ofs_y"]]
        packed.extend(bitmap[start:start + count])
    result = {
        "line_height": scalar("line_height"), "base_line": scalar("base_line"),
        "bpp": bpp, "glyphs": subset, "bitmap": base64.b64encode(packed).decode("ascii"),
        "source_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
    }
    if not dseg:
        result.update(
            kern_left=_array(source, "kern_left_class_mapping")[:96],
            kern_right=_array(source, "kern_right_class_mapping")[:96],
            kern_values=_array(source, "kern_class_values"),
            kern_right_count=scalar("right_class_cnt"), kern_scale=scalar("kern_scale"),
        )
    return result


def generate(input_dir: Path, output: Path) -> None:
    fonts = {}
    for name in FONT_NAMES:
        file_name = "lv_font_dseg_90_bpp1.c" if name == "dseg90" else f"lv_font_montserrat_{name}.c"
        fonts[name] = extract_font(input_dir / file_name, name == "dseg90")
    payload = base64.b85encode(zlib.compress(json.dumps(fonts, separators=(",", ":")).encode(), 9)).decode("ascii")
    output.write_text(
        '"""Device clock bitmap fonts, generated by tools/generate_clock_font_data.py.\n\n'
        'Unmodified glyphs: DSEG by keshikan (OFL-1.1), Montserrat project authors\n'
        '(OFL-1.1), LVGL font tables (MIT). Full notices and source references:\n'
        'assets/licenses/clock-preview-fonts.txt. Do not edit the encoded data.\n'
        '"""\n\n'
        'import base64\nimport json\nimport zlib\nfrom functools import lru_cache\n\n\n'
        '_FONT_DATA = (\n' + ''.join(f'    {line!r}\n' for line in textwrap.wrap(payload, 100)) + ')\n\n\n'
        '@lru_cache(maxsize=1)\ndef load_clock_fonts():\n'
        '    """Decode the bundled LVGL glyph metrics, kerning and bitmaps once."""\n'
        '    fonts = json.loads(zlib.decompress(base64.b85decode(_FONT_DATA)))\n'
        '    for font in fonts.values():\n'
        '        font["bitmap"] = base64.b64decode(font["bitmap"])\n'
        '        font["glyphs"] = {int(code): tuple(value) for code, value in font["glyphs"].items()}\n'
        '    return fonts\n', encoding="utf-8",
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input_dir", type=Path)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "clock_font_data.py")
    args = parser.parse_args()
    generate(args.input_dir, args.output)
